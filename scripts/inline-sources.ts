import {
  readdirSync,
  readFileSync,
  existsSync,
  writeFileSync,
  mkdirSync,
  cpSync,
  rmSync,
} from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { execFileSync } from "node:child_process";
import type { DemoMeta } from "../src/registry/types";

export interface DemoSources {
  moduleSource: string;
  htmlSource: string;
}

/**
 * Read every `<demosRoot>/<id>/{demo.js,index.html}` pair and return the raw
 * file text keyed by demo id. Directories missing either file are skipped, so
 * a half-authored demo never emits partial sources. Raw bytes are preserved
 * verbatim so the shown code equals the code that runs in the iframe.
 */
export function collectSources(demosRoot: string): Record<string, DemoSources> {
  const out: Record<string, DemoSources> = {};
  if (!existsSync(demosRoot)) return out;
  for (const entry of readdirSync(demosRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(demosRoot, entry.name);
    const modulePath = join(dir, "demo.js");
    const htmlPath = join(dir, "index.html");
    if (!existsSync(modulePath) || !existsSync(htmlPath)) continue;
    out[entry.name] = {
      moduleSource: readFileSync(modulePath, "utf8"),
      htmlSource: readFileSync(htmlPath, "utf8"),
    };
  }
  return out;
}

/**
 * Dynamically import every `<demosRoot>/<id>/meta.ts` (one file per demo —
 * see registry/types.ts DemoMeta doc) and return the default export keyed by
 * demo id. Bun evaluates the .ts import directly, no separate compile step.
 */
export async function collectMeta(
  demosRoot: string,
): Promise<Record<string, DemoMeta>> {
  const out: Record<string, DemoMeta> = {};
  if (!existsSync(demosRoot)) return out;
  for (const entry of readdirSync(demosRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const metaPath = join(demosRoot, entry.name, "meta.ts");
    if (!existsSync(metaPath)) continue;
    const mod = (await import(pathToFileURL(metaPath).href)) as {
      default: DemoMeta;
    };
    out[entry.name] = mod.default;
  }
  return out;
}

function renderSourcesModule(map: Record<string, DemoSources>): string {
  return (
    "// Generated by scripts/inline-sources.ts — do not edit by hand.\n" +
    'import type { DemoSources } from "../../scripts/inline-sources";\n\n' +
    "export const GENERATED_SOURCES: Record<string, DemoSources> = " +
    JSON.stringify(map, null, 2) +
    ";\n"
  );
}

function renderMetaModule(map: Record<string, DemoMeta>): string {
  return (
    "// Generated by scripts/inline-sources.ts — do not edit by hand.\n" +
    'import type { DemoMeta } from "./types";\n\n' +
    "export const GENERATED_META: Record<string, DemoMeta> = " +
    JSON.stringify(map, null, 2) +
    ";\n"
  );
}

/**
 * Mirror each authored demo dir into `public/demos/<id>/` so it is served as a
 * real static route (`/demos/<id>/`) with a genuine document URL. This is what
 * the sandboxed iframe loads via `src` — a `srcdoc` iframe has base URL
 * `about:srcdoc`, so the demo's `./demo.js` and `/no-ff-webgpu.js` script refs
 * can't resolve there. `src/demos/` stays the single committed source of truth;
 * `public/demos/` is generated (gitignored) and rebuilt from scratch each run.
 */
function copyDemosToPublic(demosRoot: string, publicDemos: string): number {
  rmSync(publicDemos, { recursive: true, force: true });
  if (!existsSync(demosRoot)) return 0;
  let n = 0;
  for (const entry of readdirSync(demosRoot, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const dir = join(demosRoot, entry.name);
    if (
      !existsSync(join(dir, "demo.js")) ||
      !existsSync(join(dir, "index.html"))
    )
      continue;
    mkdirSync(join(publicDemos, entry.name), { recursive: true });
    // meta.ts is authoring-only metadata, not part of what the iframe loads
    // (only demo.js + index.html are) — excluding it keeps astro check from
    // trying to typecheck a copy that has no tsconfig path resolution from
    // public/.
    cpSync(dir, join(publicDemos, entry.name), {
      recursive: true,
      filter: (src) => !src.endsWith("meta.ts"),
    });
    n++;
  }
  return n;
}

async function main(): Promise<void> {
  const here = dirname(fileURLToPath(import.meta.url));
  const demosRoot = join(here, "..", "src", "demos");
  const registryDir = join(here, "..", "src", "registry");
  const sources = collectSources(demosRoot);
  writeFileSync(
    join(registryDir, "generated-sources.ts"),
    renderSourcesModule(sources),
  );
  const meta = await collectMeta(demosRoot);
  const metaPath = join(registryDir, "generated-meta.ts");
  writeFileSync(metaPath, renderMetaModule(meta));
  // renderMetaModule's JSON.stringify nests arrays/objects that prettier
  // reflows (unlike generated-sources.ts, whose values are single escaped
  // strings prettier can't reformat) — run it here so the committed file
  // always matches format:check without a manual step after regenerating.
  execFileSync("prettier", ["--write", metaPath]);
  const copied = copyDemosToPublic(
    demosRoot,
    join(here, "..", "public", "demos"),
  );
  console.log(
    `inline-sources: wrote ${Object.keys(sources).length} demo source(s) + ${Object.keys(meta).length} meta entr(y/ies); mirrored ${copied} demo dir(s) to public/demos/`,
  );
}

if (import.meta.main) void main();
